/**
 * The lotus-aperture mark.
 *
 * Two rings of petals turning around one centre: an outer ring of lotus
 * leaves and an inner ring of aperture blades, each blade leaning so the
 * whole thing reads as a shutter mid-turn. The inner ring stops short of a
 * full circle, which leaves the opening that reads as a C, and the accent
 * dot sits in that opening.
 *
 *   node scripts/logo-lotus.mjs          writes the SVGs
 *   node scripts/logo-lotus.mjs --png    also renders previews to check
 */
import fs from "node:fs";
import path from "node:path";

const OUT = "public/brand/marks";
const S = 200; // viewBox
const C = S / 2;

/**
 * One petal, as a leaf: two quadratic curves bulging either side of a
 * radius. `r0`/`r1` are where it starts and ends from the centre, `w` is
 * how fat it gets at its waist.
 */
function petal(r0, r1, w, rotate, bias = 0) {
  const rm = (r0 + r1) / 2;
  // `bias` slides the waist along the radius: a petal whose widest point is
  // past halfway reads as a leaf, before halfway as a blade.
  const rw = rm + (r1 - r0) * bias;
  const p = (r, o) => `${(C + r).toFixed(2)},${(C + o).toFixed(2)}`;
  const d = `M${p(r0, 0)} Q${p(rw, w)} ${p(r1, 0)} Q${p(rw, -w)} ${p(r0, 0)} Z`;
  return `<path d="${d}" transform="rotate(${rotate.toFixed(2)} ${C} ${C})"/>`;
}

function build({ petals = 12, gapFrom = 0, gapCount = 0 } = {}) {
  const step = 360 / petals;
  const outer = [];
  const inner = [];

  for (let i = 0; i < petals; i++) {
    const a = i * step;
    // Outer ring: broad lotus leaves, waist past the midpoint so they come
    // to a point at the tip.
    outer.push(petal(42, 96, 26, a, 0.1));

    // Inner ring: narrower blades, leaning by a third of a step so the ring
    // spirals rather than radiates. The gap is where the C opens.
    const inGap = gapCount > 0 && (i - gapFrom + petals) % petals < gapCount;
    if (!inGap) inner.push(petal(5, 74, 25, a + step * 0.44, -0.16));
  }

  return { outer: outer.join("\n    "), inner: inner.join("\n    ") };
}

/**
 * The mark. `tone` is the petal colour, `dot` the accent.
 *
 * Petals are separated by a stroke in the background colour rather than by
 * a real gap: at 24px in the nav, modelled gaps close up and the mark turns
 * into a blob, while a stroke stays exactly one pixel wide at every size.
 */
function svg({ tone = "currentColor", dot = "#d71921", rule = "var(--mark-rule, #f4f4f4)" } = {}) {
  const { outer, inner } = build({ petals: 12, gapFrom: 10, gapCount: 3 });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}" fill="none" role="img" aria-label="Classy Captures">
  <g fill="${tone}" stroke="${rule}" stroke-width="3" stroke-linejoin="round">
    ${outer}
  </g>
  <g fill="${tone}" stroke="${rule}" stroke-width="3.5" stroke-linejoin="round">
    ${inner}
  </g>
  <circle cx="${C + 20}" cy="${C - 10}" r="19" fill="${dot}"/>
</svg>
`;
}

fs.mkdirSync(OUT, { recursive: true });
const files = {
  // Takes its colour from the text around it, so one file serves the bar on
  // paper and the bar on ink.
  "cc-lotus.svg": svg({ tone: "currentColor", rule: "none" }),
  "cc-lotus-ink.svg": svg({ tone: "#040404", rule: "#f4f4f4" }),
  "cc-lotus-paper.svg": svg({ tone: "#f4f4f4", rule: "#040404" }),
};
for (const [name, body] of Object.entries(files)) {
  fs.writeFileSync(path.join(OUT, name), body);
  console.log("wrote", path.join(OUT, name), body.length + "b");
}

// The React component, from the same geometry so there is one source of
// truth. It has to be inline SVG rather than an <img>: the petals are
// `currentColor` and inherit the colour of whatever they sit in, which an
// <img> cannot do.
const inner = svg()
  .replace(/^<svg[^>]*>\n/, "")
  .replace(/<\/svg>\s*$/, "")
  // JSX wants these camelCased; React silently drops the hyphenated forms.
  .replace(/stroke-width=/g, "strokeWidth=")
  .replace(/stroke-linejoin=/g, "strokeLinejoin=")
  .trimEnd()
  .split("\n")
  .map((l) => "      " + l)
  .join("\n");

const DOC = [
  "/**",
  " * The studio mark: a lotus of aperture blades, with the accent dot in the",
  " * opening they leave.",
  " *",
  " * Inline rather than an <img>, because the petals are `currentColor` and",
  " * take the colour of whatever they sit in. The hairlines between petals",
  " * are `--mark-rule`, which must be set to the colour behind the mark —",
  " * without them twelve overlapping petals merge into a single blob at any",
  " * size, which is exactly what it does on a ground that does not set it.",
  " */",
].join("\n");

fs.writeFileSync(
  "components/primitives/Mark.tsx",
  [
    "// GENERATED by scripts/logo-lotus.mjs — do not edit by hand.",
    "",
    DOC,
    'export default function Mark({ className = "" }: { className?: string }) {',
    "  return (",
    '    <svg viewBox="0 0 200 200" fill="none" role="img" aria-label="Classy Captures" className={className}>',
    inner,
    "    </svg>",
    "  );",
    "}",
    "",
  ].join("\n"),
);
console.log("wrote components/primitives/Mark.tsx");

if (process.argv.includes("--png")) {
  const sharp = (await import("sharp")).default;
  for (const [name, body] of Object.entries(files)) {
    if (name === "cc-lotus.svg") continue;
    const png = name.replace(".svg", ".png");
    await sharp(Buffer.from(body)).resize(360, 360).png().toFile(path.join(OUT, png));
    console.log("rendered", png);
  }
}
